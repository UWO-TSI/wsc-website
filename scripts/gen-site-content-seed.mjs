/*
  Writes the site_content seed migration from src/lib/site-content-defaults.ts,
  so the compiled-in defaults and the database seed are one list.

    node --experimental-strip-types scripts/gen-site-content-seed.mjs [out.sql]

  Defaults to the original seed migration. Once that migration is applied,
  regenerate into a NEW migration file instead: applied migrations are
  history and are never edited. ON CONFLICT DO NOTHING means a re-run seeds
  only keys that do not exist yet and never overwrites copy the club wrote.
*/
import { writeFileSync } from 'node:fs';
import { SITE_CONTENT, CONTENT_PAGES } from '../src/lib/site-content-defaults.ts';

const out = process.argv[2] ?? 'supabase/migrations/20260929000002_site_content_seed.sql';

/** @param {string | undefined} v */
const q = (v) => (v === undefined ? 'NULL' : `'${v.replaceAll("'", "''")}'`);

const entries = Object.entries(SITE_CONTENT);

for (const [key, e] of entries) {
  if (e.value.length > e.max) throw new Error(`${key}: default is ${e.value.length} chars, ceiling ${e.max}`);
  if (/[\r\n\t]|\s{2,}/.test(e.value)) throw new Error(`${key}: default is not a single normalised line`);
  if (!CONTENT_PAGES.includes(e.page)) throw new Error(`${key}: unknown page ${e.page}`);
}

/* display_order is the registry order, so the admin shows sections and
   fields in the order they appear on the page. */
const rows = entries.map(([key, e], i) => {
  const n = (i + 1) * 10;
  return `  (${[q(key), q(e.value), q(e.kind), e.max, q(e.page), q(e.section), q(e.label), q(e.help), n].join(', ')})`;
});

const sql = `-- ================================================================
-- 20260929000002_site_content_seed.sql: seed every editable string
-- ================================================================
-- GENERATED by scripts/gen-site-content-seed.mjs from
-- src/lib/site-content-defaults.ts. Do not edit by hand.
--
-- Values are the copy currently on the staging frontend, so applying
-- this changes nothing visually. ON CONFLICT DO NOTHING: re-running
-- never overwrites copy the club has since edited.
--
-- ${entries.length} keys across ${CONTENT_PAGES.length} admin tabs.
-- ================================================================

INSERT INTO public.site_content
  (key, value, kind, max_length, page, section, label, help, display_order)
VALUES
${rows.join(',\n')}
ON CONFLICT (key) DO NOTHING;


-- ----------------------------------------------------------------
-- SEED STATS: the three figures in the home About slab.
-- Only seeds when the table is empty, so it never resurrects stats
-- the club has deliberately deleted.
-- ----------------------------------------------------------------
INSERT INTO public.site_stats (value, suffix, label, visible, display_order)
SELECT * FROM (VALUES
  (150, '+', 'Members',           true, 10),
  (10,  '+', 'Annual events',     true, 20),
  (5,   '+', 'Industry partners', true, 30)
) AS seed(value, suffix, label, visible, display_order)
WHERE NOT EXISTS (SELECT 1 FROM public.site_stats);
`;

writeFileSync(out, sql);
console.log(`Wrote ${entries.length} keys to ${out}`);
